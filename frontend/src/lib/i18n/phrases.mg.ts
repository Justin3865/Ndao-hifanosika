export const PHRASES_MG: Readonly<Record<string, string>> = Object.freeze(Object.fromEntries(PAIRS));

/** Normalise une chaîne pour la recherche : apostrophes, ellipses, entités, espaces. */
export function normalizeKey(s: string): string {
  return s.replace(/\u00a0/g, " ").replace(/[’‘]/g, "'").replace(/…/g, "...").replace(/&apos;/g, "'").replace(/&amp;/g, "&").replace(/\s+/g, " ").trim();
}

const INDEX: Map<string, string> = new Map(Object.entries(PHRASES_MG).map(([k, v]) => [normalizeKey(k), v]));

/** Traduit une phrase exacte (en conservant les espaces autour). Inconnue -> inchangée. */
const DAYS_MG: Record<string, string> = { lundi: "Alatsinainy", mardi: "Talata", mercredi: "Alarobia", jeudi: "Alakamisy", vendredi: "Zoma", samedi: "Asabotsy", dimanche: "Alahady" };
const MONTHS_MG: Record<string, string> = {
  janvier: "Janoary", février: "Febroary", fevrier: "Febroary", mars: "Martsa", avril: "Aprily", mai: "Mey", juin: "Jona",
  juillet: "Jolay", août: "Aogositra", aout: "Aogositra", septembre: "Septambra", octobre: "Oktobra", novembre: "Novambra", décembre: "Desambra", decembre: "Desambra",
};

/** Phrases à trous (nombres, noms, dates) que le dictionnaire exact ne peut pas couvrir. Retourne null si aucune règle ne s'applique. */
function translatePattern(key: string): string | null {
  let m = /^(lundi|mardi|mercredi|jeudi|vendredi|samedi|dimanche) (\d{1,2})(?:er)? ([A-Za-zéûÉ]+) (\d{4})$/i.exec(key);
  if (m) {
    const month = MONTHS_MG[m[3].toLowerCase()];
    if (month) return `${DAYS_MG[m[1].toLowerCase()]} ${m[2]} ${month} ${m[4]}`;
  }
  m = /^Export « (.+) » téléchargé\.$/.exec(key);
  if (m) return `Voasintona ny fanondranana « ${translatePhrase(m[1])} ».`;
  m = /^Supprimer « (.+) » \?$/.exec(key);
  if (m) return `Hofafana ve « ${m[1]} » ?`;
  m = /^(\d+) (document|projet|activité|bénéficiaire|évaluation|stage)\(s\)$/.exec(key);
  if (m) {
    const nouns: Record<string, string> = { document: "taratasy", projet: "tetikasa", "activité": "hetsika", "bénéficiaire": "mpahazo tombontsoa", "évaluation": "fanombanana", stage: "stage" };
    return `${m[1]} ${nouns[m[2]]}`;
  }
  return null;
}

export function translatePhrase(text: string): string {
  const key = normalizeKey(text);
  const hit = key ? INDEX.get(key) ?? translatePattern(key) ?? undefined : undefined;
  if (!hit) return text;
  const lead = /^\s*/.exec(text)![0];
  const trail = /\s*$/.exec(text)![0];
  return lead + hit + trail;
}

