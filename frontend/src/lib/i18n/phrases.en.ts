export const PHRASES_EN: Readonly<Record<string, string>> = Object.freeze(Object.fromEntries(PAIRS));

/** Same normalisation as phrases.mg.ts: apostrophes, ellipses, entities, spaces. */
export function normalizeKeyEn(s: string): string {
  return s.replace(/\u00a0/g, " ").replace(/[’‘]/g, "'").replace(/…/g, "...").replace(/&apos;/g, "'").replace(/&amp;/g, "&").replace(/\s+/g, " ").trim();
}

const INDEX: Map<string, string> = new Map(Object.entries(PHRASES_EN).map(([k, v]) => [normalizeKeyEn(k), v]));

const MONTHS_EN: Record<string, string> = {
  janvier: "January", février: "February", fevrier: "February", mars: "March", avril: "April", mai: "May", juin: "June",
  juillet: "July", août: "August", aout: "August", septembre: "September", octobre: "October", novembre: "November", décembre: "December", decembre: "December",
};
const DAYS_EN: Record<string, string> = { lundi: "Monday", mardi: "Tuesday", mercredi: "Wednesday", jeudi: "Thursday", vendredi: "Friday", samedi: "Saturday", dimanche: "Sunday" };

/** Phrases with blanks (numbers, names, dates). Returns null when no rule applies. */
function translatePattern(key: string): string | null {
  let m = /^(lundi|mardi|mercredi|jeudi|vendredi|samedi|dimanche) (\d{1,2})(?:er)? ([A-Za-zéûÉ]+) (\d{4})$/i.exec(key);
  if (m) {
    const month = MONTHS_EN[m[3].toLowerCase()];
    if (month) return `${DAYS_EN[m[1].toLowerCase()]}, ${month} ${m[2]}, ${m[4]}`;
  }
  m = /^Export « (.+) » téléchargé\.$/.exec(key);
  if (m) return `Export “${translatePhraseEn(m[1])}” downloaded.`;
  m = /^Supprimer « (.+) » \?$/.exec(key);
  if (m) return `Delete “${m[1]}”?`;
  m = /^(\d+) (document|projet|activité|bénéficiaire|évaluation|stage)\(s\)$/.exec(key);
  if (m) {
    const nouns: Record<string, string> = { document: "document(s)", projet: "project(s)", "activité": "activity(ies)", "bénéficiaire": "beneficiary(ies)", "évaluation": "evaluation(s)", stage: "internship(s)" };
    return `${m[1]} ${nouns[m[2]]}`;
  }
  return null;
}

/** Translates an exact phrase (keeping surrounding spaces). Unknown -> unchanged. */
export function translatePhraseEn(text: string): string {
  const key = normalizeKeyEn(text);
  const hit = key ? INDEX.get(key) ?? translatePattern(key) ?? undefined : undefined;
  if (!hit) return text;
  const lead = /^\s*/.exec(text)![0];
  const trail = /\s*$/.exec(text)![0];
  return lead + hit + trail;
}

